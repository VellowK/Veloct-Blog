    #[test]
    fn both_modes_mark_the_working_tree_changed_and_require_an_index_rebuild() {
        // handoff.md section 17.10: after a content restore the working tree is considered changed,
        // no Release is generated automatically, and the content index is rebuilt.
        assert!(RestoreMode::Full.marks_working_tree_changed());
        assert!(RestoreMode::ContentOnly.marks_working_tree_changed());
        assert!(RestoreMode::ContentOnly.preserves_history());
        assert!(!RestoreMode::Full.preserves_history(), "a full restore replaces history too");

        let source = project();
        let archive = backup(&source);
        let staging = TempDir::new().unwrap();
        for mode in [RestoreMode::Full, RestoreMode::ContentOnly] {
            let staged = Restore::stage(&archive, mode, staging.path()).unwrap();
            let outcome = Restore::apply(&staged, source.path(), true).unwrap();
            assert!(outcome.working_tree_changed);
            assert!(outcome.needs_index_rebuild);
            assert!(outcome.summary().contains("publish again"));
        }
    }

    #[test]
    fn a_restore_of_a_non_veloct_archive_is_refused() {
        let dir = TempDir::new().unwrap();
        let archive_path = dir.path().join("random.tar.gz");
        // A plain gzip of nothing relevant.
        let file = fs::File::create(&archive_path).unwrap();
        let encoder = flate2::write::GzEncoder::new(file, flate2::Compression::default());
        let mut builder = tar::Builder::new(encoder);
        let mut header = tar::Header::new_gnu();
        header.set_size(1);
        header.set_cksum();
        builder
            .append_data(&mut header, "x.txt", &b"y"[..])
            .unwrap();
        builder.into_inner().unwrap().finish().unwrap();

        let staging = TempDir::new().unwrap();
        let error = Restore::stage(&archive_path, RestoreMode::Full, staging.path()).unwrap_err();
        assert!(error.to_string().contains("not a Veloct backup"), "{error}");
    }

    #[test]
    fn a_staged_restore_and_an_outcome_round_trip_through_json() {
        let source = project();
        let archive = backup(&source);
        let staging = TempDir::new().unwrap();
        let staged = Restore::stage(&archive, RestoreMode::ContentOnly, staging.path()).unwrap();

        let json = serde_json::to_string(&staged).unwrap();
        assert!(json.contains("\"content_only\""), "{json}");
        assert_eq!(serde_json::from_str::<StagedRestore>(&json).unwrap(), staged);

        let outcome = Restore::apply(&staged, source.path(), true).unwrap();
        let json = serde_json::to_string(&outcome).unwrap();
        assert!(json.contains("\"files_written\""), "{json}");
        assert_eq!(serde_json::from_str::<RestoreOutcome>(&json).unwrap(), outcome);
    }
