//! Publishing: the only path that creates a commit, and the release tag that anchors it.
//!
//! `handoff.md` §14.3 and §14.4 define the lifecycle:
//!
//! ```text
//! working tree -> change detection -> publish commit -> release tag -> one Astro build
//! ```
//!
//! and §2.5 adds the rule that makes the whole thing trustworthy: **autosave never creates a
//! commit**. The commit function here is the only one in the workspace, it is only reachable
//! through [`commit_publish`], and it refuses to run without a real change.

use std::path::Path;

use git2::{Oid, Repository, Signature};
use serde::{Deserialize, Serialize};

use veloct_core::{ReleaseId, Result, VeloctError};

use crate::change::{changes, ChangeSet};

/// The prefix every release tag carries. `handoff.md` §14.4 step 3.
pub const TAG_PREFIX: &str = "release/";

/// What a publish produced.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub enum CommitOutcome {
    /// Nothing to record. No commit was created (`handoff.md` §14.3 step 3, row A7).
    NoChange,
    /// A publish commit was created.
    Committed(PublishCommit),
}

impl CommitOutcome {
    pub fn commit(&self) -> Option<&PublishCommit> {
        match self {
            Self::NoChange => None,
            Self::Committed(commit) => Some(commit),
        }
    }

    pub fn sha(&self) -> Option<&str> {
        self.commit().map(|commit| commit.sha.as_str())
    }

    pub fn is_no_change(&self) -> bool {
        matches!(self, Self::NoChange)
    }
}

/// A created publish commit.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct PublishCommit {
    pub id: String,
    pub sha: String,
    pub message: String,
    /// What the commit recorded, so the UI can report it.
    pub changes: ChangeSet,
}

/// A release tag and the commit it points at.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ReleaseTag {
    /// Full tag name, `release/<release-id>`.
    pub name: String,
    pub release_id: ReleaseId,
    pub commit_sha: String,
}

/// A tag discovered in the repository.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct TagRef {
    pub name: String,
    pub commit_sha: String,
}

/// The default publish commit message.
///
/// Generated by the program, never typed by the user (`handoff.md` §14.3).
pub fn publish_message(release_id: &ReleaseId, changes: &ChangeSet) -> String {
    format!("release({release_id}): {}", changes.summary())
}

/// The signature used for publish commits.
///
/// A machine without a configured Git identity must still be able to publish, so Veloct falls back
/// to the project's local configuration and then to a clearly-labelled default. The default is
/// obviously synthetic so nobody mistakes it for a real author.
fn signature(repository: &Repository) -> Result<Signature<'static>> {
    if let Ok(signature) = repository.signature() {
        return Ok(signature);
    }
    Signature::now("Veloct", "veloct@localhost").map_err(|e| {
        VeloctError::Git(format!(
            "no Git author is configured and a default could not be built: {e}"
        ))
    })
}

/// Create the publish commit for a release.
///
/// Ordering follows `handoff.md` §14.4: the caller writes the release manifest *before* calling
/// this, so the manifest is part of the commit. The manifest itself must not contain this commit's
/// sha, which is why the sha is returned rather than written back into it.
pub fn commit_publish(
    repository: &Repository,
    release_id: &ReleaseId,
    message: Option<&str>,
) -> Result<CommitOutcome> {
    let change_set = changes(repository)?;

    // An unresolved merge conflict must never be committed as a release (`handoff.md` §20.3).
    if change_set.has_conflicts() {
        let files: Vec<String> = change_set
            .conflicts()
            .iter()
            .map(|file| file.path.clone())
            .collect();
        return Err(VeloctError::MergeConflict(files.join(", ")));
    }

    if change_set.is_empty() {
        return Ok(CommitOutcome::NoChange);
    }

    let mut index = repository
        .index()
        .map_err(|e| VeloctError::Git(format!("could not read the index: {e}")))?;
    index
        .add_all(["*"].iter(), git2::IndexAddOption::DEFAULT, None)
        .map_err(|e| VeloctError::Git(format!("could not stage the working tree: {e}")))?;
    index
        .write()
        .map_err(|e| VeloctError::Git(format!("could not write the index: {e}")))?;

    let tree_id = index
        .write_tree()
        .map_err(|e| VeloctError::Git(format!("could not write the tree: {e}")))?;
    let tree = repository
        .find_tree(tree_id)
        .map_err(|e| VeloctError::Git(format!("could not read the tree: {e}")))?;

    let parent = match repository.head() {
        Ok(head) => Some(head.peel_to_commit().map_err(|e| {
            VeloctError::Git(format!("could not resolve HEAD to a commit: {e}"))
        })?),
        Err(_) => None, // The very first commit has no parent.
    };
    let parents: Vec<&git2::Commit> = parent.iter().collect();

    let signature = signature(repository)?;
    let text = match message {
        Some(text) => text.to_string(),
        None => publish_message(release_id, &change_set),
    };

    let oid = repository
        .commit(Some("HEAD"), &signature, &signature, &text, &tree, &parents)
        .map_err(|e| VeloctError::Git(format!("could not create the publish commit: {e}")))?;

    Ok(CommitOutcome::Committed(PublishCommit {
        id: oid.to_string(),
        sha: oid.to_string(),
        message: text,
        changes: change_set,
    }))
}

/// Create the release tag that anchors a release to its commit.
///
/// A lightweight tag is used deliberately: it *is* the commit reference, so `release/<id>` cannot
/// drift from the commit it names through a re-tag of the tag object itself.
pub fn create_release_tag(repository: &Repository, release_id: &ReleaseId) -> Result<ReleaseTag> {
    let head = repository
        .head()
        .map_err(|e| VeloctError::Git(format!("the repository has no commit to tag: {e}")))?;
    let commit = head
        .peel_to_commit()
        .map_err(|e| VeloctError::Git(format!("could not resolve HEAD to a commit: {e}")))?;

    let name = release_id.tag_name();
    // `force = false` makes an existing tag an error, which is what is wanted: a release id must
    // never be reused for a different commit (`handoff.md` §23.1).
    repository
        .tag_lightweight(&name, commit.as_object(), false)
        .map_err(|e| {
            VeloctError::Git(format!(
                "could not create the tag {name} (release ids must be unique): {e}"
            ))
        })?;

    Ok(ReleaseTag {
        name,
        release_id: release_id.clone(),
        commit_sha: commit.id().to_string(),
    })
}

/// Create a release tag pointing at an explicit commit.
///
/// Used by the re-send and rollback flows, which tag the *original* commit rather than HEAD
/// (`handoff.md` §14.13, §14.14).
pub fn create_release_tag_at(
    repository: &Repository,
    release_id: &ReleaseId,
    commit_sha: &str,
) -> Result<ReleaseTag> {
    let oid = Oid::from_str(commit_sha)
        .map_err(|e| VeloctError::Git(format!("{commit_sha:?} is not a commit id: {e}")))?;
    let object = repository
        .find_object(oid, None)
        .map_err(|e| VeloctError::Git(format!("commit {commit_sha} was not found: {e}")))?;

    let name = release_id.tag_name();
    repository
        .tag_lightweight(&name, &object, false)
        .map_err(|e| VeloctError::Git(format!("could not create the tag {name}: {e}")))?;

    Ok(ReleaseTag {
        name,
        release_id: release_id.clone(),
        commit_sha: commit_sha.to_string(),
    })
}

/// Whether a release tag already exists.
pub fn tag_exists(repository: &Repository, release_id: &ReleaseId) -> bool {
    repository
        .find_reference(&format!("refs/tags/{}", release_id.tag_name()))
        .is_ok()
}

/// Resolve the commit a release tag points at.
///
/// This is the read half of "truth = release.json + git tag + the commit it points to"
/// (`handoff.md` §14.4, §21.1).
pub fn commit_for_tag(repository: &Repository, release_id: &ReleaseId) -> Result<String> {
    let name = release_id.tag_name();
    let reference = repository
        .find_reference(&format!("refs/tags/{name}"))
        .map_err(|e| VeloctError::Git(format!("release tag {name} was not found: {e}")))?;
    let object = reference
        .peel(git2::ObjectType::Commit)
        .map_err(|e| VeloctError::Git(format!("tag {name} does not point at a commit: {e}")))?;
    Ok(object.id().to_string())
}

/// List every release tag, sorted by name.
pub fn list_release_tags(repository: &Repository) -> Result<Vec<TagRef>> {
    let names = repository
        .tag_names(None)
        .map_err(|e| VeloctError::Git(format!("could not list tags: {e}")))?;

    let mut tags = Vec::new();
    for index in 0..names.len() {
        // `get` returns `Result<Option<&str>>`: the Result reports an out-of-range index and the
        // Option reports a non-UTF-8 entry, and neither should abort listing the rest.
        let Ok(Some(name)) = names.get(index) else {
            continue;
        };
        if !name.starts_with(TAG_PREFIX) {
            continue;
        }        let full = format!("refs/tags/{name}");
        let Ok(reference) = repository.find_reference(&full) else {
            continue;
        };
        let Ok(object) = reference.peel(git2::ObjectType::Commit) else {
            continue;
        };
        tags.push(TagRef {
            name: name.to_string(),
            commit_sha: object.id().to_string(),
        });
    }
    tags.sort_by(|a, b| a.name.cmp(&b.name));
    Ok(tags)
}

/// Check out a commit into a separate worktree for a historical rebuild.
///
/// `handoff.md` §14.13 requires a failed sub-target to be re-sent from the original commit, and
/// §14.14 requires a rollback to rebuild from a release tag. Both need the tree of an old commit
/// without disturbing the user's working tree, which is what a linked worktree provides.
///
/// The worktree is created on a temporary branch because a worktree reference must resolve to a
/// branch; `delete_worktree` removes both the worktree bookkeeping and that branch.
pub fn worktree_at(repository: &Repository, commit_sha: &str, path: &Path) -> Result<()> {
    let oid = Oid::from_str(commit_sha)
        .map_err(|e| VeloctError::Git(format!("{commit_sha:?} is not a commit id: {e}")))?;
    let commit = repository
        .find_commit(oid)
        .map_err(|e| VeloctError::Git(format!("commit {commit_sha} was not found: {e}")))?;

    let short: String = commit_sha.chars().take(12).collect();
    let name = format!("veloct-{short}");
    let branch_name = format!("veloct/rebuild/{short}");

    // Reuse the branch across repeated rebuilds of the same release rather than failing on a
    // leftover from an interrupted run.
    let branch = match repository.find_branch(&branch_name, git2::BranchType::Local) {
        Ok(branch) => branch,
        Err(_) => repository
            .branch(&branch_name, &commit, false)
            .map_err(|e| {
                VeloctError::Git(format!("could not create the rebuild branch {branch_name}: {e}"))
            })?,
    };
    let reference = branch.into_reference();

    let mut options = git2::WorktreeAddOptions::new();
    options.reference(Some(&reference));

    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).map_err(|e| VeloctError::io(parent, e))?;
    }

    // A worktree left behind by an interrupted rebuild would make this fail; remove it first.
    if let Ok(existing) = repository.find_worktree(&name) {
        if existing.is_prunable(None).unwrap_or(false) {
            let _ = existing.prune(None);
        }
    }

    repository.worktree(&name, path, Some(&options)).map_err(|e| {
        VeloctError::Git(format!(
            "could not create a worktree for {commit_sha} at {}: {e}",
            path.display()
        ))
    })?;
    Ok(())
}

/// Remove a worktree created by [`worktree_at`], including its temporary branch.
///
/// `handoff.md` §14.13 requires the temporary build products to be deleted afterwards, so this is
/// the counterpart that keeps the repository from accumulating rebuild worktrees.
pub fn remove_worktree(repository: &Repository, commit_sha: &str) -> Result<()> {
    let short: String = commit_sha.chars().take(12).collect();
    let name = format!("veloct-{short}");

    let worktree = repository
        .find_worktree(&name)
        .map_err(|e| VeloctError::Git(format!("worktree {name} was not found: {e}")))?;
    worktree
        .prune(Some(
            git2::WorktreePruneOptions::new()
                .valid(true)
                .working_tree(true),
        ))
        .map_err(|e| VeloctError::Git(format!("could not remove worktree {name}: {e}")))?;

    let branch_name = format!("veloct/rebuild/{short}");
    if let Ok(mut branch) = repository.find_branch(&branch_name, git2::BranchType::Local) {
        let _ = branch.delete();
    }
    Ok(())
}

