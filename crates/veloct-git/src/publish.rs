    fn count_commits(repository: &Repository) -> usize {
        let mut walk = repository.revwalk().unwrap();
        walk.push_head().unwrap();
        walk.count()
    }

    /// Leave an open repository in the middle of an unresolved merge conflict.
    ///
    /// Takes the repository by reference rather than returning one: a `Commit` borrows the
    /// repository for its whole lifetime, so building this inline and returning the repository is
    /// rejected by the borrow checker.
    fn build_conflict(repository: &Repository, path: &std::path::Path) {
        write_atomic(&path.join("shared.md"), b"base\n").unwrap();
        commit_publish(repository, &release(20), None).unwrap();
        write_atomic(&path.join("unrelated.md"), b"x\n").unwrap();
        commit_publish(repository, &release(21), None).unwrap();

        let base = {
            let base = repository
                .revparse_single("HEAD~1")
                .unwrap()
                .peel_to_commit()
                .unwrap();
            base.id()
        };

        // `mainline` changes shared.md one way; `feature` changes the same line another way.
        {
            let base_commit = repository.find_commit(base).unwrap();
            repository.branch("mainline", &base_commit, true).unwrap();
            repository.branch("feature", &base_commit, true).unwrap();
        }

        repository.set_head("refs/heads/mainline").unwrap();
        repository
            .checkout_head(Some(git2::build::CheckoutBuilder::new().force()))
            .unwrap();
        write_atomic(&path.join("shared.md"), b"main change\n").unwrap();
        commit_publish(repository, &release(22), None).unwrap();

        repository.set_head("refs/heads/feature").unwrap();
        repository
            .checkout_head(Some(git2::build::CheckoutBuilder::new().force()))
            .unwrap();
        write_atomic(&path.join("shared.md"), b"feature change\n").unwrap();
        let outcome = commit_publish(repository, &release(23), None).unwrap();
        assert!(outcome.commit().is_some(), "the feature branch must commit");

        let main = repository
            .find_reference("refs/heads/mainline")
            .unwrap()
            .peel_to_commit()
            .unwrap();
        let annotated = repository.find_annotated_commit(main.id()).unwrap();
        let mut checkout = git2::build::CheckoutBuilder::new();
        checkout.force();
        repository
            .merge(&[&annotated], None, Some(&mut checkout))
            .unwrap();
    }
