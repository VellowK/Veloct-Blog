        assert!(first.commit().is_some(), "the first publish has the scaffold to commit");

        let second = commit_publish(&fixture.repository, &release_id, None).unwrap();
        assert!(second.is_no_change(), "{second:?}");

        // And the branch really did not grow.
        let count = count_commits(&fixture.repository);
